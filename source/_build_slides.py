#!/usr/bin/env python3
"""Регенерирует js/slides.js из master.json (импорт мастер-деки Влада: _import_master.py) + overrides.json (1-based индексы слайдов; ключ "by": заголовок — переживает перестановки)."""
import json, re, os
here=os.path.dirname(os.path.abspath(__file__)); root=os.path.dirname(here)
S=json.load(open(os.path.join(here,'master.json')))
OV=json.load(open(os.path.join(here,'overrides.json')))
import html as _h
def _strip(t): return re.sub(r'[^\w$]+',' ',_h.unescape(re.sub(r'<[^>]+>',' ',t or '')).lower()).strip()
bytitle={_strip(s['t']):s for s in S}
for k,v in OV.items():
    # Source-bound split overrides are materialized by _foundation_prepare.py.
    if k.startswith('__') or (v.get('presentationParts') or {}).get('sourceGoogleObjectId'): continue
    tgt=None
    if k.isdigit(): tgt=S[int(k)-1]
    else: tgt=bytitle.get(_strip(k))
    if tgt is None: print("!! override not matched:",k); continue
    tgt.update(v)
ACTS=json.load(open(os.path.join(here,'acts.json')))
DIR=open(os.path.join(here,'dir.js'),encoding='utf-8').read()
order=['a','lv','mvp','kind','fx','k','t','b','note','st','bg','bgside','bgpos','photos','ptall','lost','src','poster','beats','img','ar','caps','bar','bar2','rows','cta','dirk','disc']
out=[]
for s in S:
    o={k:s[k] for k in order if k in s}
    for k in s:
        if k not in o: o[k]=s[k]
    out.append(o)
body=",\n".join(json.dumps(o,ensure_ascii=False) for o in out)
txt=f"""/* AI-Оператор · преза эфира · данные слайдов (генерируется source/_build_slides.py — правь slides-v3.json / overrides.json или прямо здесь)
   a — акт · lv — уровень дофаминовой кривой 1–10 · mvp — входит в 60-мин версию
   kind — hero|text|screen|video|meme|embed|stack|price|cta|qa · fx — спецэффект (stop|prizes|flash|button|g96)
   k — кикер · t — заголовок · b — html-тело · note — заметка спикера · st — статус
   bg/bgside/bgpos — фотофон · photos/ptall — сетка фото · lost — «потеря» (обесцветить)
   src/poster/beats — видео с битами · img/ar/caps/bar — мем · rows — стек · cta — текст кнопки */
window.CTA_URL = "#ОПЛАТА"; /* [НУЖНО ОТ КОМАНДЫ: реальная ссылка брони $10] */
window.ACTS = {json.dumps(ACTS,ensure_ascii=False,indent=1)};
window.S = [
{body}
];
/* режиссёрские карточки: «место|задача слайда|показать/сделать|мысль зрителю», ключ — заголовок или dirk */
window.DIR = {DIR};
"""
open(os.path.join(root,'js','slides.js'),'w',encoding='utf-8').write(txt)
if '__google180' in OV:
    G=OV['__google180']['slides']
    gtxt='/* Generated by source/_build_slides.py from overrides.__google180. */\nwindow.CTA_URL="#ОПЛАТА";\nwindow.ACTS='+json.dumps(ACTS,ensure_ascii=False)+';\nwindow.DIR={};\nwindow.S='+json.dumps(G,ensure_ascii=False)+';\n'
    open(os.path.join(root,'js','slides-google180.js'),'w',encoding='utf-8').write(gtxt)
    print('Google source edition:',len(G),'slides')
print("slides.js written:", len(txt.encode()), "bytes;",len(S),"slides")
